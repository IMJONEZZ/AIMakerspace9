# Kitaru checkpoints for the deep research pipeline.
# Each function represents a discrete, recoverable step in the research process.
# Decorated with @checkpoint so Kitaru can save outputs and resume from failures.

import kitaru
from langchain.chat_models import init_chat_model
from kitaru import checkpoint

# LMStudio connection settings pulled from configuration.py
